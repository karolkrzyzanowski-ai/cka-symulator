const goType = { integer: 'int32', string: 'string', boolean: 'bool', number: 'float64' };

// zwraca {unknown: [ścieżki], typeErrors: [komunikaty]}
export function strictCheck(obj, typeName) {
  const unknown = [];
  const typeErrors = [];
  const walk = (val, type, path, structName, field) => {
    if (val === null || val === undefined) return;
    if (type.startsWith('[]')) {
      if (!Array.isArray(val)) { typeErrors.push(`json: cannot unmarshal ${jsKind(val)} into Go struct field ${structName}.${path} of type []${goName(type.slice(2))}`); return; }
      val.forEach((v, i) => walk(v, type.slice(2), `${path}[${i}]`, structName, field));
      return;
    }
    if (type === 'Object') return;
    if (type.startsWith('map[')) {
      if (typeof val !== 'object' || Array.isArray(val)) { typeErrors.push(`json: cannot unmarshal ${jsKind(val)} into Go struct field ${structName}.${path} of type map[string]string`); return; }
      if (type === 'map[string]string') {
        for (const [k, v] of Object.entries(val)) {
          if (typeof v !== 'string') typeErrors.push(`json: cannot unmarshal ${jsKind(v)} into Go struct field ${structName}.${path} of type string`);
          void k;
        }
      }
      return;
    }
    if (type === 'Quantity') {
      if (typeof val !== 'string' && typeof val !== 'number') typeErrors.push(`quantities must match the regular expression '^([+-]?[0-9.]+)([eEinumkKMGTP]*[-+]?[0-9]*)$'`);
      return;
    }
    if (type === 'IntOrString') { if (typeof val === 'object') typeErrors.push(`json: cannot unmarshal ${jsKind(val)} into Go struct field ${structName}.${path} of type intstr.IntOrString`); return; }
    if (type === 'string') { if (typeof val !== 'string') typeErrors.push(`json: cannot unmarshal ${jsKind(val)} into Go struct field ${structName}.${path} of type string`); return; }
    if (type === 'integer') { if (typeof val !== 'number' || !Number.isInteger(val)) typeErrors.push(`json: cannot unmarshal ${jsKind(val)} into Go struct field ${structName}.${path} of type int32`); return; }
    if (type === 'boolean') { if (typeof val !== 'boolean') typeErrors.push(`json: cannot unmarshal ${jsKind(val)} into Go struct field ${structName}.${path} of type bool`); return; }
    if (type === 'number') return;
    const st = T[type];
    if (!st) return;
    if (typeof val !== 'object' || Array.isArray(val)) { typeErrors.push(`json: cannot unmarshal ${jsKind(val)} into Go struct field ${structName}.${path} of type v1.${type}`); return; }
    for (const [k, v] of Object.entries(val)) {
      if (k === '_d') continue;
      const fs = st[k];
      const p = path ? `${path}.${k}` : k;
      if (!fs) { unknown.push(p); continue; }
      walk(v, parseFieldType(fs).type, p, type, k);
    }
  };
  const jsKind = (v) => (Array.isArray(v) ? 'array' : v === null ? 'null' : typeof v === 'object' ? 'object' : typeof v === 'boolean' ? 'bool' : typeof v);
  const goName = (t) => (goType[t] || (T[t] ? `v1.${t}` : t));
  walk(obj, typeName, '', typeName, '');
  return { unknown, typeErrors };
}

// --------------------------------------------------------------------------- explain
function wrapText(text, width = 76, indent = '    ') {
  const words = String(text).split(/\s+/);
  const lines = [];
  let cur = '';
  for (const w of words) {
    if ((cur + ' ' + w).trim().length > width) { lines.push(cur.trim()); cur = w; } else cur += ' ' + w;
  }
  if (cur.trim()) lines.push(cur.trim());
  return lines.map((l) => indent + l).join('\n');
}

function typeLabel(t) {
  if (t.startsWith('[]')) {
    const inner = t.slice(2);
    return `[]${T[inner] ? 'Object' : inner}`;
  }
  if (t.startsWith('map[')) return 'map[string]string';
  if (T[t]) return 'Object';
  if (t === 'IntOrString') return 'IntOrString';
  if (t === 'Quantity') return 'Quantity';
  return t;
}

export function explainType(group, kind, version, typeName, fieldPath, { recursive = false } = {}) {
  let cur = typeName, desc = T[typeName]?._d || '', label = null, path = [];
  for (const seg of fieldPath) {
    const st = T[cur.replace(/^\[\]/, '')];
    if (!st || !st[seg]) return { error: `error: field "${seg}" does not exist` };
    const f = parseFieldType(st[seg]);
    path.push(seg);
    desc = f.desc || T[f.type.replace(/^\[\]/, '')]?._d || '';
    label = typeLabel(f.type) + (f.required ? ' -required-' : '');
    cur = f.type;
  }
  const lines = [];
  if (group) lines.push(`GROUP:      ${group}`);
  lines.push(`KIND:       ${kind}`);
  lines.push(`VERSION:    ${version}`);
  lines.push('');
  if (path.length) { lines.push(`FIELD: ${path[path.length - 1]} <${label.replace(' -required-', '')}>`); lines.push(''); }
  lines.push('DESCRIPTION:');
  lines.push(wrapText(desc || '<empty>'));
  lines.push('    ');
  const st = T[cur.replace(/^\[\]/, '')];
  if (st) {
    lines.push('FIELDS:');
    const emit = (stName, indent, seen) => {
      const s = T[stName];
      for (const [k, v] of Object.entries(s)) {
        if (k === '_d') continue;
        const f = parseFieldType(v);
        const inner = f.type.replace(/^\[\]/, '');
        if (recursive) {
          lines.push(`${indent}${k}\t<${typeLabel(f.type)}>${f.required ? ' -required-' : ''}`);
          if (T[inner] && !seen.includes(inner) && seen.length < 8) emit(inner, indent + '  ', [...seen, inner]);
        } else {
          lines.push(`  ${k}\t<${typeLabel(f.type)}>${f.required ? ' -required-' : ''}`);
          lines.push(wrapText(f.desc || T[inner]?._d || '<no description>'));
          lines.push('');
        }
      }
    };
    emit(cur.replace(/^\[\]/, ''), '  ', [cur]);
  }
  return { text: lines.join('\n').replace(/\n+$/, '') + '\n\n' };
}

// explain dla CRD (openAPIV3Schema)
export function explainSchema(group, kind, version, schema, fieldPath, { recursive = false } = {}) {
  let cur = schema || {};
  const path = [];
  for (const seg of fieldPath) {
    const props = cur.type === 'array' ? cur.items?.properties : cur.properties;
    if (!props || !props[seg]) return { error: `error: field "${seg}" does not exist` };
    cur = props[seg];
    path.push(seg);
  }
  const lbl = (s) => (s.type === 'array' ? `[]${s.items?.type === 'object' ? 'Object' : s.items?.type || 'Object'}` : s.type === 'object' ? (s.additionalProperties ? 'map[string]string' : 'Object') : s.type || 'Object');
  const lines = [];
  if (group) lines.push(`GROUP:      ${group}`);
  lines.push(`KIND:       ${kind}`);
  lines.push(`VERSION:    ${version}`);
  lines.push('');
  if (path.length) { lines.push(`FIELD: ${path[path.length - 1]} <${lbl(cur)}>`); lines.push(''); }
  lines.push('DESCRIPTION:');
  lines.push(wrapText(cur.description || '<empty>'));
  if (cur.enum) { lines.push('    '); lines.push(`    ENUM:`); for (const e of cur.enum) lines.push(`        ${e}`); }
  lines.push('    ');
  const props = cur.type === 'array' ? cur.items?.properties : cur.properties;
  if (props) {
    lines.push('FIELDS:');
    const req = new Set((cur.type === 'array' ? cur.items?.required : cur.required) || []);
    const emit = (ps, rq, indent, depth) => {
      for (const [k, v] of Object.entries(ps)) {
        lines.push(`${recursive ? indent : '  '}${k}\t<${lbl(v)}>${rq.has(k) ? ' -required-' : ''}`);
        if (recursive) {
          const sub = v.type === 'array' ? v.items?.properties : v.properties;
          if (sub && depth < 8) emit(sub, new Set((v.type === 'array' ? v.items?.required : v.required) || []), indent + '  ', depth + 1);
        } else {
          lines.push(wrapText(v.description || '<no description>'));
          if (v.enum) { lines.push(''); lines.push('    ENUM:'); for (const e of v.enum) lines.push(`        ${e}`); }
          lines.push('');
        }
      }
    };
    emit(props, req, '  ', 0);
  }
  return { text: lines.join('\n').replace(/\n+$/, '') + '\n\n' };
}

// walidacja według openAPIV3Schema (CRD)
export function validateSchema(val, schema, path = '') {
  const errs = [];
  const unknown = [];
  const walk = (v, s, p) => {
    if (!s || s['x-kubernetes-preserve-unknown-fields']) return;
    if (v === null || v === undefined) return;
    const t = s.type;
    if (t === 'object') {
      if (typeof v !== 'object' || Array.isArray(v)) { errs.push(`${p}: Invalid value: "${typeof v}": ${p} in body must be of type object: "${Array.isArray(v) ? 'array' : typeof v}"`); return; }
      for (const r of s.required || []) if (v[r] === undefined) errs.push(`${p ? p + '.' : ''}${r}: Required value`);
      if (s.properties) {
        for (const [k, x] of Object.entries(v)) {
          const cp = p ? `${p}.${k}` : k;
          if (s.properties[k]) walk(x, s.properties[k], cp);
          else if (s.additionalProperties) walk(x, s.additionalProperties === true ? {} : s.additionalProperties, cp);
          else if (!['apiVersion', 'kind', 'metadata', 'status'].includes(k) || p) unknown.push(cp);
        }
      }
    } else if (t === 'array') {
      if (!Array.isArray(v)) { errs.push(`${p}: Invalid value: "${typeof v}": ${p} in body must be of type array: "${typeof v}"`); return; }
      v.forEach((x, i) => walk(x, s.items, `${p}[${i}]`));
    } else if (t === 'string') {
      if (typeof v !== 'string') errs.push(`${p}: Invalid value: "${typeof v === 'number' ? 'integer' : typeof v}": ${p} in body must be of type string: "${typeof v === 'number' ? 'integer' : typeof v}"`);
      else if (s.enum && !s.enum.includes(v)) errs.push(`${p}: Unsupported value: "${v}": supported values: ${s.enum.map((e) => `"${e}"`).join(', ')}`);
    } else if (t === 'integer') {
      if (typeof v !== 'number' || !Number.isInteger(v)) errs.push(`${p}: Invalid value: "${typeof v}": ${p} in body must be of type integer: "${typeof v}"`);
      else {
        if (s.minimum !== undefined && v < s.minimum) errs.push(`${p}: Invalid value: ${v}: ${p} in body should be greater than or equal to ${s.minimum}`);
        if (s.maximum !== undefined && v > s.maximum) errs.push(`${p}: Invalid value: ${v}: ${p} in body should be less than or equal to ${s.maximum}`);
      }
    } else if (t === 'boolean') {
      if (typeof v !== 'boolean') errs.push(`${p}: Invalid value: "${typeof v}": ${p} in body must be of type boolean: "${typeof v}"`);
    } else if (t === 'number') {
      if (typeof v !== 'number') errs.push(`${p}: Invalid value: "${typeof v}": ${p} in body must be of type number: "${typeof v}"`);
    }
  };
  walk(val, schema, path);
  return { errs, unknown };
}

// wartości domyślne ze schematu CRD
export function applySchemaDefaults(val, schema) {
  if (!schema || val === null || typeof val !== 'object') return;
  if (schema.type === 'object' && schema.properties) {
    for (const [k, s] of Object.entries(schema.properties)) {
      if (val[k] === undefined && s.default !== undefined) val[k] = JSON.parse(JSON.stringify(s.default));
      if (val[k] !== undefined) applySchemaDefaults(val[k], s);
    }
  } else if (schema.type === 'array' && Array.isArray(val)) {
    for (const x of val) applySchemaDefaults(x, schema.items);
  }
}
